import argparse
import json
import re
from pathlib import Path

SKIP = re.compile(r"^(destructor|Shutdown|Release.*|BReleaseSteamPipe|BShutdownIfAllPipesClosed|ExitGameServer|LogOff|LogOn.*|"
                  r".*(Delete|Purchase|Trade|Gift|Kick|Publish|Submit|Subscribe|Remove|Overlay|Restart|Quit|Exit|Logon|LogOff|"
                  r"Abandon|Leave|Invite|Disband|Launch|Commit|Join|Send|Upload|Accept|Decline|Ban|Block|Report|Share|Vote|Reset|"
                  r"Show|Binding|Panel|Browser|OpenURL|OpenSteam|TextInput|Notification|StoreStats|SetPersonaName|SetPlayedWith|CreateLobby|CreateItem|ResetAll|Cloud|FileWrite|FileDelete|FileShare).*)$")

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="catalog/catalog.json")
    ap.add_argument("--out", default="tests/conformance/probe_table.h")
    a = ap.parse_args(argv)
    cat = json.loads(Path(a.catalog).read_text())
    lines = ["/* Generated by tools/conformance/gen_table.py; do not edit. */", "typedef struct { const char *iface; int n; const char *const *methods; const unsigned char *skip; const unsigned char *hidden; } ProbeIface;"]
    names = []
    for i in cat["interfaces"]:
        slots = i.get("slots")
        if not slots:
            continue
        ident = re.sub(r"\W", "_", i["name"])
        lines.append(f'static const char *const m_{ident}[] = {{ ' + ", ".join(f'"{s["name"]}"' for s in slots) + " };")
        lines.append(f'static const unsigned char h_{ident}[] = {{ ' + ", ".join("1" if s.get("ret") == "struct8" else "0" for s in slots) + " };")
        lines.append(f'static const unsigned char s_{ident}[] = {{ ' + ", ".join("1" if SKIP.match(s["name"]) else "0" for s in slots) + " };")
        names.append((i["name"], ident, len(slots)))
    lines.append("static const ProbeIface g_probe[] = {")
    for n, ident, c in names:
        lines.append(f'    {{ "{n}", {c}, m_{ident}, s_{ident}, h_{ident} }},')
    lines.append("};")
    lines.append(f"enum {{ PROBE_COUNT = {len(names)} }};")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"{len(names)} interfaces -> {a.out}")

if __name__ == "__main__":
    main()
