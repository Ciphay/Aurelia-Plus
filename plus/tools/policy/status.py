import argparse
import collections
import glob
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent

def interface_type(name):
    return re.sub(r"(_?V(ERSION_?)?)?\d{3}$", "", name)

def implemented_methods(source_dir):
    pairs = set()
    for path in glob.glob(str(Path(source_dir) / "*.c")):
        src = Path(path).read_text()
        variables = {}
        for m in re.finditer(r'const char \*(\w+)\s*=\s*"([^"]+)"\s*;|shim_register(?:_family(?:_ab)?)?\(\s*([^,]+?)\s*,\s*"(\w+)"', src):
            if m.group(1):
                variables[m.group(1)] = m.group(2)
                continue
            first = m.group(3).strip()
            prefix = first[1:-1] if first.startswith('"') else variables.get(first)
            pairs.add((prefix, m.group(4)))
        for m in re.finditer(r'reg\("(\w+)"', src):
            pairs.add((None, m.group(1)))
        for m in re.finditer(r'\{\s*"(\w+)"\s*,\s*\(void \*\)', src):
            pairs.add((None, m.group(1)))
        for block in re.findall(r"static const char \*const \w+\[\] = \{([^}]*)\}", src):
            for name in re.findall(r'"(\w+)"', block):
                pairs.add((None, name))
    return pairs

def classify(catalog, policy, implemented):
    reviewed = collections.defaultdict(set)
    for prefix, kinds in policy.items():
        for methods in kinds.values():
            reviewed[prefix].update(methods)
    out = collections.defaultdict(dict)
    for iface in catalog["interfaces"]:
        t = interface_type(iface["name"])
        for s in iface["slots"] or []:
            m = s["name"]
            if m in out[t]:
                continue
            if any(meth == m and (pre is None or iface["name"].startswith(pre)) for pre, meth in implemented):
                out[t][m] = "impl"
            elif any(m in reviewed[p] for p in reviewed if iface["name"].startswith(p)):
                out[t][m] = "policy"
            elif re.fullmatch(r"Unknown\d+", m):
                out[t][m] = "recovered"
            elif s.get("ret") == "call":
                out[t][m] = "net"
            else:
                out[t][m] = "pending"
    return out

def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m tools.policy.status")
    ap.add_argument("--pending", metavar="KIND", help="list the pending methods of a kind (prefix)")
    ap.add_argument("--markdown", action="store_true", help="coverage report in Markdown")
    a = ap.parse_args(argv)
    catalog = json.loads((ROOT / "catalog/catalog.json").read_text())
    policy = json.loads((ROOT / "catalog/policy.json").read_text())
    res = classify(catalog, policy, implemented_methods(ROOT / "shim/ifaces"))
    if a.pending:
        meta = {}
        for iface in catalog["interfaces"]:
            for s in iface["slots"] or []:
                meta.setdefault((interface_type(iface["name"]), s["name"]), (s.get("ret", "?"), s.get("argbytes32")))
        for t in sorted(res):
            if t.startswith(a.pending):
                print(f"## {t}")
                print(", ".join(f"{m}[{meta[(t, m)][0]},{meta[(t, m)][1]}]" for m, k in sorted(res[t].items()) if k == "pending"))
        return
    if a.markdown:
        print("# Shim surface: coverage per interface\n")
        print("Generated by `python -m tools.policy.status --markdown`. Each row counts the distinct methods of an interface kind"
              " (all versions):\n")
        print("- **impl**: C implementation with its own behavior.")
        print("- **policy**: reviewed method whose default (0, empty, accepted, constant) is the right answer.")
        print("- **net**: returns an asynchronous result (`SteamAPICall_t`); without the Steam network it completes as an I/O failure.")
        print("- **pending**: not reviewed yet (Phase A only ends at 0).\n")
        print("| Interface | impl | policy | net | pending |\n|---|---:|---:|---:|---:|")
        total = collections.Counter()
        for t in sorted(res):
            c = collections.Counter(res[t].values())
            total.update(c)
            print(f"| {t} | {c['impl']} | {c['policy']} | {c['net']} | {c['pending']} |")
        print(f"| **Total** | **{total['impl']}** | **{total['policy']}** | **{total['net']}** | **{total['pending']}** |")
        return
    total = collections.Counter()
    for t in sorted(res):
        c = collections.Counter(res[t].values())
        total.update(c)
        print(f"{t:44s} impl={c['impl']:3d} policy={c['policy']:3d} net={c['net']:3d} pending={c['pending']:3d}")
    print(f"{'TOTAL':44s} impl={total['impl']:3d} policy={total['policy']:3d} net={total['net']:3d} pending={total['pending']:3d}")

if __name__ == "__main__":
    main()
