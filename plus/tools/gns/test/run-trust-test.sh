#!/usr/bin/env bash
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
work=${GNS_WORK:-$here/../../../run/gns}; work=$(cd "$work" && pwd)
app=${1:-480}
aurelia=${AURELIA_BIN:-$here/../../../../aurelia/target/release/aurelia}
proton="$HOME/.local/share/Steam/steamapps/common/Proton - Experimental/proton"
tmp=$(mktemp -d "$work/trust-XXXX")
curl -s -m 30 "https://api.steampowered.com/ISteamApps/GetSDRConfig/v1/?appid=$app" -o "$tmp/sdr.json"
python3 -I -c 'import json,sys; [print(c) for c in json.load(open(sys.argv[1]))["certs"]]' "$tmp/sdr.json" > "$tmp/certs.txt"
[[ -n "${NO_CERTS:-}" ]] && : > "$tmp/certs.txt"
echo "SDR configuration certificates: $(wc -l < "$tmp/certs.txt")"
win() { echo "Z:${1//\//\\}"; }
mkdir -p "$tmp/compat"
export STEAM_COMPAT_DATA_PATH="$tmp/compat" STEAM_COMPAT_CLIENT_INSTALL_PATH="$HOME/.local/share/Steam" WINEDEBUG=-all
python3 "$proton" run "$work/gns_trust_test-x86_64.exe" "$(win "$tmp/pub.txt")" "$(win "$tmp/signed.b64")" "$(win "$tmp/certs.txt")" "$(win "$tmp/result.txt")" "$app" > "$tmp/prog.log" 2>&1 &
prog=$!
for _ in $(seq 1 300); do [[ -s "$tmp/pub.txt" ]] && break; sleep 1; done
[[ -s "$tmp/pub.txt" ]] || { echo "the library did not generate the public key"; cat "$tmp/prog.log"; exit 1; }
pub=$(tr -d '\r\n' < "$tmp/pub.txt"); echo "public key generated by the library: $pub"
"$aurelia" kill > /dev/null 2>&1 || true
"$aurelia" debug-cert "$app" --key "$pub" 2>&1 | grep '^SIGNED_B64' | cut -d' ' -f2 > "$tmp/signed.b64"
[[ -s "$tmp/signed.b64" ]] || { echo "Steam did not return a certificate"; exit 1; }
wait "$prog" || true
echo "--- result"; cat "$tmp/result.txt" 2>/dev/null || { echo "(no result)"; cat "$tmp/prog.log"; }
